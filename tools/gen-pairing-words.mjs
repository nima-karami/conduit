// `node tools/gen-pairing-words.mjs <english.txt> --sha256 <hex>` writes src/network/pairing-words.ts
// from the BIP-39 English list. The hash is a required argument rather than a constant here so the
// person regenerating states which upstream file they checked (plan 2026-11-14-conduit-network
// T2.4: cross-checked against a second source before use).

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [file, flag, expected] = process.argv.slice(2);
if (!file || flag !== '--sha256' || !/^[0-9a-f]{64}$/.test(expected ?? '')) {
  console.error('usage: node tools/gen-pairing-words.mjs <english.txt> --sha256 <hex>');
  process.exit(2);
}
const bytes = readFileSync(file);
const got = createHash('sha256').update(bytes).digest('hex');
if (got !== expected) {
  console.error(`gen-pairing-words: sha256 ${got}, expected ${expected}`);
  process.exit(1);
}
const words = bytes.toString('utf8').split('\n').filter(Boolean);
// 2048 keeps newCode's draw unbiased (a power of two) and the 3-word code at 33 bits.
if (words.length !== 2048 || words.some((w) => !/^[a-z]+$/.test(w))) {
  console.error(`gen-pairing-words: expected 2048 lowercase words, got ${words.length}`);
  process.exit(1);
}
const rows = [];
for (let i = 0; i < words.length; i += 8) {
  rows.push(
    `  ${words
      .slice(i, i + 8)
      .map((w) => `'${w}'`)
      .join(', ')},`,
  );
}
const out = `// Generated by tools/gen-pairing-words.mjs from the BIP-39 English word list (BSD-2-Clause,
// see THIRD_PARTY_NOTICES.txt), sha256 ${got}. Do not edit by hand.
export const PAIRING_WORDS: readonly string[] = [
${rows.join('\n')}
];
`;
writeFileSync('src/network/pairing-words.ts', out);
console.log(`gen-pairing-words: wrote ${words.length} words`);
